    n_i = random.choice([10, 14, 20, 28, 36, 50]); n_c = n_i + random.choice([-2, 0, 2])
    sd = 12.0
    mi = round(random.gauss(6.0 + (3.0 if n_i <= 14 else 0.0), 2.5), 2)   # small studies slightly larger: asymmetry for Egger
    mc = round(random.gauss(0.5, 2.0), 2)
    pool += rct_pair(f"synth_a05_rct_{j:02d}", f"SYN-P05-{j}", "A05", "RMSSD change", "ms", "breathing",
                     mi, sd, n_i, mc, round(sd * random.uniform(0.9, 1.1), 1), n_c)
